    for e, ns in emojis.items():
        if len(ns) > 1:
            errs.append(f"이모지 중복 {e}: {ns}")
    nameset = set(names)
    keys = {}
    for a, b, r in recs:
        for x in (a, b, r):
            if x not in nameset:
                errs.append(f"없는 원소: {a}+{b}={r} ({x})")
        k = tuple(sorted((a, b)))
        if k in keys and keys[k] != r:
            errs.append(f"충돌: {a}+{b} → {keys[k]} / {r}")
        keys[k] = r
    # 도달 가능성
    found = set(BASE)
    order = []
    changed = True
    while changed:
        changed = False
        for a, b, r in recs:
            if a in found and b in found and r not in found:
                found.add(r)
                order.append(r)
                changed = True
    unreach = [n for n in names if n not in found]
    if unreach:
        errs.append("도달 불가: " + ", ".join(unreach))
    # 레시피 없는 원소 / 재료로 안 쓰이는 원소
    results = {r for _, _, r in recs}
    norecipe = [n for n in names if n not in results and n not in BASE]
    if norecipe:
        errs.append("레시피 없음: " + ", ".join(norecipe))
    used = set()
    for a, b, _ in recs:
        used.add(a); used.add(b)
    deadend = [n for n in names if n not in used]
    return errs, deadend, order


